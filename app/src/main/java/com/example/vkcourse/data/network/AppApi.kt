package com.example.vkcourse.data.network

/**
 * Асинхронный источник рейтингов приложений.
 *
 * В учебном проекте для рейтинга нет отдельного эндпоинта, поэтому реализация
 * эмулирует сетевой запрос через delay. Интерфейс вынесен отдельно от
 * Retrofit-описания [CatalogApi], чтобы задержку можно было заменить
 * настоящим запросом, не меняя слой репозитория.
 */
interface AppApi {
    suspend fun getRating(id: String): Float
}
